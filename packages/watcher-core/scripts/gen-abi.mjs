// Generates src/generated/abi.ts from the forge artifacts in contracts/out, so the watcher never carries a
// hand-copied event ABI. `--check` exits 1 when the committed file differs from what the current artifacts produce;
// test/abi-drift.test.ts runs the same comparison (and skips when contracts/out has not been built).
//
//   cd contracts && forge build && cd ../packages/watcher-core && node scripts/gen-abi.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..", "..");
export const OUT_DIR = join(ROOT, "contracts", "out");
export const INTERFACES_SOL = join(ROOT, "contracts", "src", "account", "interfaces.sol");
export const TARGET = join(here, "..", "src", "generated", "abi.ts");

const art = (file, name) => JSON.parse(readFileSync(join(OUT_DIR, file, `${name}.json`), "utf8")).abi;

const sig = (item) => `${item.type}:${item.name}(${(item.inputs ?? []).map((i) => i.type).join(",")})`;

/** Events and errors of several artifacts, deduplicated by signature and sorted by name (stable output). */
function merge(abis) {
  const seen = new Set();
  const out = [];
  for (const item of abis.flat()) {
    if (item.type !== "event" && item.type !== "error") continue;
    const key = sig(item);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
  }
  return out.sort((a, b) => `${a.type}${a.name}${sig(a)}`.localeCompare(`${b.type}${b.name}${sig(b)}`));
}

/** ERC-7579 module type ids (`library ModuleType` constants: not in any ABI). */
function moduleTypes() {
  const src = readFileSync(INTERFACES_SOL, "utf8");
  const lib = src.slice(src.indexOf("library ModuleType"));
  const out = {};
  for (const m of lib.slice(0, lib.indexOf("}")).matchAll(/uint256 internal constant ([A-Z_]+) = (\d+);/g))
    out[m[1]] = Number(m[2]);
  return out;
}

export async function render() {
  const account = art("LeanAccount.sol", "LeanAccount");
  const keystore = art("KeystoreValidator.sol", "KeystoreValidator");
  const hook = art("SpendingLimitHook.sol", "SpendingLimitHook");
  const recovery = art("GuardianRecovery.sol", "GuardianRecovery");
  const j = (v) => JSON.stringify(v, null, 2);
  const text = `// GENERATED by scripts/gen-abi.mjs from contracts/out (forge artifacts). Do not edit.
// Regenerate after \`forge build\`; test/abi-drift.test.ts fails when this file is stale.

/** \`LeanAccount\` (each watched account emits these itself): events + errors. */
export const accountAbi = ${j(merge([account]))} as const;

/**
 * The account's shared modules: \`KeystoreValidator\`, \`SpendingLimitHook\`, \`GuardianRecovery\`. One deployment serves
 * every account, so their events carry \`account\` as the first indexed topic.
 */
export const modulesAbi = ${j(merge([keystore, hook, recovery]))} as const;

/** ERC-7579 module type ids (\`ModuleType\` in contracts/src/account/interfaces.sol). */
export const MODULE_TYPES = ${j(moduleTypes())} as const;
`;
  const options = (await prettier.resolveConfig(TARGET)) ?? {};
  return prettier.format(text, { ...options, filepath: TARGET });
}

export const artifactsPresent = () =>
  ["LeanAccount", "KeystoreValidator", "SpendingLimitHook", "GuardianRecovery"].every((n) =>
    existsSync(join(OUT_DIR, `${n}.sol`, `${n}.json`)),
  );

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await render();
  if (process.argv.includes("--check")) {
    const cur = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
    if (cur !== text) {
      console.error("src/generated/abi.ts is stale: run `node scripts/gen-abi.mjs`");
      process.exit(1);
    }
    console.log("abi.ts is up to date");
  } else {
    writeFileSync(TARGET, text);
    console.log(`wrote ${TARGET}`);
  }
}
