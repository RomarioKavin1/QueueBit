// Generates src/generated/abi.ts from the forge artifacts in contracts/out, so the watcher never carries a
// hand-copied event ABI. `--check` exits 1 when the committed file differs from what the current artifacts produce;
// test/abi-drift.test.ts runs the same comparison (and skips when contracts/out has not been built).
//
//   cd contracts && forge build && cd ../packages/watcher-core && node scripts/gen-abi.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..", "..");
export const OUT_DIR = join(ROOT, "contracts", "out");
export const BASE_SOL = join(ROOT, "contracts", "src", "account", "LeakedAccountBase.sol");
export const TARGET = join(here, "..", "src", "generated", "abi.ts");

const art = (file, name) => JSON.parse(readFileSync(join(OUT_DIR, file, `${name}.json`), "utf8")).abi;

/** Not watched: OpenZeppelin plumbing that every upgradeable contract emits. */
const SKIP_EVENTS = new Set(["EIP712DomainChanged", "Initialized"]);

const sig = (item) => `${item.type}:${item.name}(${(item.inputs ?? []).map((i) => i.type).join(",")})`;

/** Events and errors of several artifacts, deduplicated by signature and sorted by name (stable output). */
function merge(abis, { events = true, errors = true, only } = {}) {
  const seen = new Set();
  const out = [];
  for (const item of abis.flat()) {
    if (item.type === "event" ? !events || SKIP_EVENTS.has(item.name) : item.type === "error" ? !errors : true)
      continue;
    if (only && !only.includes(item.name)) continue;
    const key = sig(item);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
  }
  return out.sort((a, b) => `${a.type}${a.name}${sig(a)}`.localeCompare(`${b.type}${b.name}${sig(b)}`));
}

/** The `KIND_*` constants of the queue (they are public constants, so their values are not in the ABI). */
function kinds() {
  const src = readFileSync(BASE_SOL, "utf8");
  const out = {};
  for (const m of src.matchAll(/uint8 public constant KIND_([A-Z]+) = (\d+);/g)) out[m[1]] = Number(m[2]);
  return out;
}

export async function render() {
  const impl = art("LeakedAccountImpl.sol", "LeakedAccountImpl");
  const roles = art("LeakedAccountRoles.sol", "LeakedAccountRoles");
  const hook = art("LeakedPolicyHook.sol", "LeakedPolicyHook");
  const executor = art("LeakedRoleExecutor.sol", "LeakedRoleExecutor");
  const entryPoint = art("IEntryPoint.sol", "IEntryPoint");
  const roleSigner = art("PQRoleSigner.sol", "PQRoleSigner");
  const hotExecute = impl.filter((x) => x.type === "function" && x.name === "hotExecute");
  const j = (v) => JSON.stringify(v, null, 2);
  const text = `// GENERATED by scripts/gen-abi.mjs from contracts/out (forge artifacts). Do not edit.
// Regenerate after \`forge build\`; test/abi-drift.test.ts fails when this file is stale.

/** Frame-native account (\`LeakedAccountImpl\` + the \`LeakedAccountRoles\` module behind its fallback): events + errors. */
export const frameAccountAbi = ${j(merge([impl, roles]))} as const;

/** \`hotExecute(declaredUsd, calls)\`: the SENDER frame of every hot transaction. */
export const hotExecuteAbi = ${j(hotExecute)} as const;

/** ERC-4337/7579 backend (\`LeakedPolicyHook\` + \`LeakedRoleExecutor\`): events (account-indexed) + errors. */
export const moduleAbi = ${j(merge([hook, executor]))} as const;

/** ERC-4337 EntryPoint: the two events a failed userOp leaves (\`IEntryPoint\`). */
export const entryPointAbi = ${j(merge([entryPoint], { errors: false, only: ["UserOperationEvent", "UserOperationRevertReason"] }))} as const;

/** \`PQRoleSigner\` (vault / recovery role signers): staking and payer events. */
export const roleSignerAbi = ${j(merge([roleSigner]))} as const;

/** Queue kinds (\`LeakedAccountBase.KIND_*\`). */
export const QUEUE_KINDS = ${j(kinds())} as const;
`;
  const options = (await prettier.resolveConfig(TARGET)) ?? {};
  return prettier.format(text, { ...options, filepath: TARGET });
}

export const artifactsPresent = () => existsSync(join(OUT_DIR, "LeakedAccountImpl.sol", "LeakedAccountImpl.json"));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await render();
  if (process.argv.includes("--check")) {
    const cur = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
    if (cur !== text) {
      console.error("src/generated/abi.ts is stale: run `node scripts/gen-abi.mjs`");
      process.exit(1);
    }
    console.log("abi.ts is up to date");
  } else {
    writeFileSync(TARGET, text);
    console.log(`wrote ${TARGET}`);
  }
}
