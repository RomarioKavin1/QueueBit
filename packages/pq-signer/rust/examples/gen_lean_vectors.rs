//! leanSphincs-s KAT set C generator:
//!   `cargo run --release --example gen_lean_vectors -- ../vectors/leansphincs-s.json`
//! 32 positive vectors {BIP-39 mnemonic -> master -> role seed (QueueBit derivation, this scheme's id) -> Light-tier
//! key (b = 13) -> hedged signature with fixed entropy} plus negative mutation recipes, for the Solidity adapter tests.
//! Test mnemonics are the public BIP-39 reference vectors: never use them for funds.
use queuebit_pq::hash::keccak256;
use queuebit_pq::lean_s::{self, params::*};
use queuebit_pq::Role;
use serde_json::json;

fn hx(b: &[u8]) -> String {
    format!("0x{}", hex::encode(b))
}

fn main() {
    let out = std::env::args().nth(1).expect("usage: gen_lean_vectors <out.json>");
    let mnemonics = [
        ("abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about", ""),
        ("legal winner thank year wave sausage worth useful legal winner thank yellow", "TREZOR"),
        ("letter advice cage absurd amount doctor acoustic avoid letter advice cage above", ""),
        ("zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo wrong", "TREZOR"),
    ];
    let mut vectors = vec![];
    let mut id = 0usize;
    for (words, pass) in mnemonics {
        let m: bip39::Mnemonic = words.parse().unwrap();
        let master = m.to_seed_normalized(pass);
        for role in [Role::Vault, Role::Recovery] {
            let seed = lean_s::derive_seed(&master, role, "any").unwrap();
            let sk = lean_s::SecretKey::from_seed(&seed);
            let pk = sk.public_key();
            for _ in 0..4 {
                let digest = match id % 16 {
                    0 => [0u8; 32],
                    15 => [0xffu8; 32],
                    _ => keccak256(format!("QueueBit leanSphincs-s KAT C digest #{id}").as_bytes()),
                };
                let entropy = keccak256(format!("QueueBit leanSphincs-s KAT C entropy #{id}").as_bytes());
                let sig = lean_s::sign_with_entropy(&sk, &digest, &entropy).unwrap();
                assert!(lean_s::verify(&pk, &digest, &sig));
                let mut w_seed = [0u8; 32];
                w_seed[..16].copy_from_slice(&pk[..16]);
                let mut w_root = [0u8; 32];
                w_root[..16].copy_from_slice(&pk[16..]);
                vectors.push(json!({
                    "id": id,
                    "mnemonic": words,
                    "passphrase": pass,
                    "master": hx(&master),
                    "role": role.label(),
                    "chainScope": "any",
                    "seed": hx(&seed[..]),
                    "pk": hx(&pk),
                    "pkSeed": hx(&w_seed),
                    "pkRoot": hx(&w_root),
                    "digest": hx(&digest),
                    "entropy": hx(&entropy),
                    "sig": hx(&sig),
                }));
                eprintln!("vector {id} done");
                id += 1;
            }
        }
    }
    let doc = json!({
        "_comment": "leanSphincs-s KAT set C (QueueBit). Generated by packages/pq-signer/rust/examples/gen_lean_vectors.rs. Positive vectors: verify(pk, digest, sig) == true for IPQVerifier/LeanSphincsSVerifier (pk = P16||root16) and LeanSphincsSAsm.verify(pkSeed, pkRoot, digest, sig) (high-aligned bytes32 words given as pkSeed/pkRoot). Keys are Light tier (kept subtree b = 13). Signatures are hedged with the given entropy (R_0 = Th(P, address(RANDOMIZER), S || digest || entropy), then upstream's grind), so re-signing reproduces them. Negative recipes apply to every positive vector and must return false (adapter) without reverting, except where 'verifierReverts' is true (raw LeanSphincsSAsm reverts on length != 4164).",
        "scheme": "leanSphincs-s over keccak256 (nconsigny/SPHINCS- 4c76aaf, src/keccak/LeanSphincs-SAsm.sol, docs/leanSphincs-S-keccak.md)",
        "experimental": true,
        "schemeIdPreimage": std::str::from_utf8(SCHEME_ID_PREIMAGE).unwrap(),
        "schemeId": hx(&SCHEME_ID),
        "sigLength": SIG_LEN,
        "keptSubtreeHeight": B,
        "signatureBudget": SIGNATURE_BUDGET,
        "derivation": "role_key = HMAC-SHA512(key = 'queuebit/v1/' || schemeId(32 raw bytes) || '/' || role || '/' || chainScope, msg = BIP-39 seed); S = role_key[0:32]; P = Th(0^16, address(PARAMETER), S); root per spec §9 with b = 13",
        "negative": [
            {"kind": "flipBit", "byteOffsets": "every offset 0..4163 (or a sample: 0, 15, 16, 31, 32, 2719, 2720, 2723, 2724, 3747, 3748, 4163)", "bit": "any", "expect": false},
            {"kind": "flipDigestBit", "byteOffsets": [0, 31], "expect": false},
            {"kind": "truncate", "length": 4163, "expect": false, "verifierReverts": true},
            {"kind": "extend", "length": 4165, "expect": false, "verifierReverts": true},
            {"kind": "empty", "length": 0, "expect": false, "verifierReverts": true},
            {"kind": "c13Length", "length": 3688, "expect": false, "verifierReverts": true},
            {"kind": "allZero", "length": 4164, "expect": false},
            {"kind": "allFF", "length": 4164, "expect": false},
            {"kind": "swapPkHalves", "expect": false},
            {"kind": "otherVectorPk", "expect": false},
            {"kind": "counterPlusOne", "byteOffsets": [2720], "note": "little-endian uint32 WOTS+C counter; the target-sum check (or the root) fails", "expect": false}
        ],
        "vectors": vectors,
    });
    std::fs::write(&out, serde_json::to_string_pretty(&doc).unwrap() + "\n").unwrap();
    eprintln!("wrote {} vectors to {out}", vectors.len());
}
