//! KAT set C generator: `cargo run --release --example gen_vectors -- ../vectors/c13.json`
//! 32 positive vectors {BIP-39 mnemonic -> master -> role key -> hedged signature with fixed
//! entropy} plus negative mutation recipes, for the Solidity verifier / adapter tests.
//! Test mnemonics are the public BIP-39 reference vectors: never use them for funds.
use queuebit_pq::derive::role_seeds;
use queuebit_pq::hash::keccak256;
use queuebit_pq::params::*;
use queuebit_pq::{Role, SecretKey};
use serde_json::json;

fn hx(b: &[u8]) -> String {
    format!("0x{}", hex::encode(b))
}

fn main() {
    let out = std::env::args().nth(1).expect("usage: gen_vectors <out.json>");
    let mnemonics = [
        ("abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about", ""),
        ("legal winner thank year wave sausage worth useful legal winner thank yellow", "TREZOR"),
        ("letter advice cage absurd amount doctor acoustic avoid letter advice cage above", ""),
        ("zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo wrong", "TREZOR"),
    ];
    let mut vectors = vec![];
    let mut id = 0usize;
    for (words, pass) in mnemonics {
        let m: bip39::Mnemonic = words.parse().unwrap();
        let master = m.to_seed_normalized(pass);
        for role in [Role::Vault, Role::Recovery] {
            let (sk_seed, pk_seed) = role_seeds(&master, role, "any").unwrap();
            let sk = SecretKey::from_seeds(&sk_seed, &pk_seed);
            let pk = sk.public_key();
            for j in 0..4 {
                let _ = j;
                let digest = match id % 16 {
                    0 => [0u8; 32],
                    15 => [0xffu8; 32],
                    _ => keccak256(format!("QueueBit KAT C digest #{id}").as_bytes()),
                };
                let entropy = keccak256(format!("QueueBit KAT C entropy #{id}").as_bytes());
                let sig = queuebit_pq::sign_with_entropy(&sk, &digest, &entropy).unwrap();
                assert!(queuebit_pq::verify(&pk.to_bytes(), &digest, &sig));
                let mut w_seed = [0u8; 32];
                w_seed[..16].copy_from_slice(&pk.pk_seed);
                let mut w_root = [0u8; 32];
                w_root[..16].copy_from_slice(&pk.pk_root);
                vectors.push(json!({
                    "id": id,
                    "mnemonic": words,
                    "passphrase": pass,
                    "master": hx(&master),
                    "role": role.label(),
                    "chainScope": "any",
                    "skSeed": hx(&sk_seed),
                    "pk": hx(&pk.to_bytes()),
                    "pkSeed": hx(&w_seed),
                    "pkRoot": hx(&w_root),
                    "digest": hx(&digest),
                    "entropy": hx(&entropy),
                    "sig": hx(&sig),
                }));
                eprintln!("vector {id} done");
                id += 1;
            }
        }
    }
    let doc = json!({
        "_comment": "KAT set C (QueueBit). Generated by packages/pq-signer/rust/examples/gen_vectors.rs. Positive vectors: verify(pk, digest, sig) == true for IPQVerifier/C13Adapter (pk = pkSeed16||pkRoot16) and SphincsC13Asm.verify(pkSeed, pkRoot, digest, sig) (top-aligned bytes32 words given as pkSeed/pkRoot). Signatures are hedged with the given entropy (R = keccak(skSeed||'R_hedge'||entropy||digest||nonce)), so re-signing reproduces them. Negative recipes apply to every positive vector and must return false (adapter) without reverting, except where 'verifierReverts' is true (raw SphincsC13Asm reverts on length != 3688).",
        "scheme": "SPHINCS- C13 (nconsigny/SPHINCS- 4c76aaf, src/keccak/SPHINCs-C13Asm.sol)",
        "schemeIdPreimage": std::str::from_utf8(SCHEME_ID_PREIMAGE).unwrap(),
        "schemeId": hx(&SCHEME_ID),
        "sigLength": SIG_LEN,
        "derivation": "role_key = HMAC-SHA512(key = 'queuebit/v1/' || schemeId(32 raw bytes) || '/' || role || '/' || chainScope, msg = BIP-39 seed); skSeed = role_key[0:32]; pkSeed = role_key[32:48]",
        "negative": [
            {"kind": "flipBit", "byteOffsets": "every offset 0..3687 (or a sample: 0, 15, 16, 127, 128, 1951, 1952, 2639, 2640, 2643, 2644, 3687)", "bit": "any", "expect": false},
            {"kind": "flipDigestBit", "byteOffsets": [0, 31], "expect": false},
            {"kind": "truncate", "length": 3687, "expect": false, "verifierReverts": true},
            {"kind": "extend", "length": 3689, "expect": false, "verifierReverts": true},
            {"kind": "empty", "length": 0, "expect": false, "verifierReverts": true},
            {"kind": "allZero", "length": 3688, "expect": false},
            {"kind": "allFF", "length": 3688, "expect": false},
            {"kind": "swapPkHalves", "expect": false},
            {"kind": "otherVectorPk", "expect": false},
            {"kind": "wotsCountPlusOne", "byteOffsets": [2640, 3508], "note": "big-endian uint32 counter of layer 0 / layer 1; target-sum check fails", "expect": false}
        ],
        "vectors": vectors,
    });
    std::fs::write(&out, serde_json::to_string_pretty(&doc).unwrap() + "\n").unwrap();
    eprintln!("wrote {} vectors to {out}", vectors.len());
}
