/**
 * @queuebit/lean-sphincs: leanVM leanSPHINCS, the post-quantum signature scheme LeanPool nodes verify and aggregate
 * (EIP-8288's `LEANSPHINCS_SCHEME`). QueueBit uses it for the post-quantum everyday key: the extension signs a frame
 * transaction's signature hash, a LeanPool node verifies the signature off-chain and batches it, and the account's
 * the LeanAccount keystore only checks the batch's Merkle root on-chain.
 *
 * WASM core (Rust crate `queuebit-lean-sphincs`, `rust/`) over leanVM `signatures` at revision `a39758d`, the one
 * `@kevaundray/lean-pq` 0.7.0 binds: keys and signatures are byte-compatible with the LeanPool node
 * (`vectors/lean-pq-0.7.0.json` is generated by native lean-pq and checked here). The WASM is inlined, so the module
 * loads unchanged in browsers, extension service workers and Node.
 *
 * Building a key (its kept subtree) is the slow step; keep the `LeanSphincsKey` and sign many times with it.
 *
 * NOT AUDITED. leanSPHINCS and its parameters are a research scheme.
 */
import { initSync, LeanSphincsKey as WasmKey, verify as wasmVerify } from "../wasm/lean_sphincs.js";
import { WASM_BASE64, WASM_SHA256 } from "../wasm/lean_sphincs_inline.js";

function fromBase64(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

initSync({ module: fromBase64(WASM_BASE64) });

/** Seed (master secret) length. */
export const SEED_LENGTH = 32;
/** Public key length: the EIP-8288 `verification_key_hash` of the triple and the LeanAccount keystore's PQ key (`KeyInit.a`). */
export const PK_LENGTH = 32;
/** Signature length at leanVM a39758d. */
export const SIG_LENGTH = 4276;
/** Message length: QueueBit signs the frame transaction's 32-byte signature hash. */
export const MESSAGE_LENGTH = 32;
/** The kept height of every QueueBit key (LeanPool's `KEPT_HEIGHT`). It changes the public key, so it is fixed. */
export const KEPT_HEIGHT = 12;
/** Signatures one key may make at the scheme's proven security bound for kept height 12 (leanVM doc/lean_sphincs). */
export const SIGNATURE_BUDGET = 120_000;
/** EIP-8288 `LEANSPHINCS_SCHEME`. */
export const LEANSPHINCS_SCHEME = 0x10;
/** QueueBit's label for this scheme and parameter set (the key-derivation label; its keccak256 is the scheme id). */
export const SCHEME_LABEL = "leanSPHINCS/leanVM/a39758d/v1";
/** sha256 of the embedded WASM binary. */
export const WASM_HASH = WASM_SHA256;

function bytes(x: Uint8Array, n: number, what: string): Uint8Array {
  if (!(x instanceof Uint8Array) || x.length !== n) throw new Error(`${what} must be ${n} bytes`);
  return x;
}

/** A leanSPHINCS secret key with its kept subtree built. Call `dispose()` when the wallet locks. */
export class LeanSphincsKey {
  private key: WasmKey | null;
  /** 32 bytes. */
  readonly publicKey: Uint8Array;

  private constructor(key: WasmKey) {
    this.key = key;
    this.publicKey = key.publicKey();
  }

  /** Builds the key from its 32-byte seed (QueueBit derives the seed from the wallet's recovery phrase). */
  static fromSeed(seed: Uint8Array, keptHeight: number = KEPT_HEIGHT): LeanSphincsKey {
    return new LeanSphincsKey(new WasmKey(bytes(seed, SEED_LENGTH, "seed"), keptHeight));
  }

  /** Signs a 32-byte message (a frame transaction's signature hash). */
  sign(message: Uint8Array): Uint8Array {
    if (!this.key) throw new Error("leanSPHINCS key was disposed");
    return this.key.sign(bytes(message, MESSAGE_LENGTH, "message"));
  }

  /** Frees the WASM memory holding the key. */
  dispose(): void {
    this.key?.free();
    this.key = null;
  }
}

/** Verifies a signature; any malformed input is simply invalid. */
export function verify(publicKey: Uint8Array, message: Uint8Array, signature: Uint8Array): boolean {
  if (publicKey.length !== PK_LENGTH || message.length !== MESSAGE_LENGTH || signature.length !== SIG_LENGTH) {
    return false;
  }
  return wasmVerify(publicKey, message, signature);
}
