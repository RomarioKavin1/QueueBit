// Writes `export const WASM_BASE64 = "..."` (+ .d.ts) next to the wasm-bindgen output.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const [, , wasmPath, outPath] = process.argv;
const bytes = readFileSync(wasmPath);
const sha256 = createHash("sha256").update(bytes).digest("hex");
writeFileSync(
  outPath,
  `// Generated by scripts/inline-wasm.mjs. Do not edit.\n` +
    `export const WASM_SHA256 = "${sha256}";\n` +
    `export const WASM_BASE64 = "${bytes.toString("base64")}";\n`,
);
writeFileSync(
  outPath.replace(/\.js$/, ".d.ts"),
  `export declare const WASM_SHA256: string;\nexport declare const WASM_BASE64: string;\n`,
);
console.log(`inlined ${bytes.length} bytes, sha256 ${sha256}`);
