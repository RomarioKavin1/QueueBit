// Regenerates contracts/test/leanpool/fixtures/pq-aggregator.json: real SPHINCS- C13 signatures over PQAggregator
// digests, for the Forge tests (which cannot sign C13 themselves). The test contracts are placed at fixed addresses
// (vm.etch / deployCodeTo), so a digest depends only on the values below. Deterministic: the keys come from fixed
// seeds and every signature uses fixed hedging entropy, so a re-run writes the same file.
//
//   pnpm --filter @queuebit/leanpool-node pin-vectors     (~10 signatures, a few seconds to ~20 s each)
import fs from "node:fs";
import { test } from "vitest";
import { bytesToHex, concat, getAddress, hexToBytes, keccak256, pad, parseEther, stringToHex, toHex } from "viem";
import type { Address, Hex } from "viem";
import * as c13 from "@queuebit/pq-signer";
import { attachDigest, postDigest, rotateDigest, withdrawDigest } from "../src/pqAggregator.js";

const OUT = new URL("../../../contracts/test/leanpool/fixtures/pq-aggregator.json", import.meta.url);
const label = (s: string) => keccak256(stringToHex(s));
const at = (s: string): Address => getAddress(`0x${label(s).slice(-40)}`);

const CHAIN_ID = 31337;
const REGISTRY = at("pq-aggregator-test.registry");
const AGGREGATOR = at("pq-aggregator-test.aggregator");
const ACCOUNT = at("pq-aggregator-test.account");
const W1 = at("pq-aggregator-test.wallet1");
const W2 = at("pq-aggregator-test.wallet2");
const PAYEE = at("pq-aggregator-test.payee");

const keyOf = (name: string) =>
  c13.keygenFromSeedParts(
    hexToBytes(label(`pq-aggregator-test.sk.${name}`)),
    hexToBytes(label(`pq-aggregator-test.pk.${name}`)).slice(0, 16),
  );

test("pin the PQAggregator C13 vectors", { timeout: 900_000 }, () => {
  const keys = { A: keyOf("A"), B: keyOf("B"), C: keyOf("C") };
  const d = { chainId: CHAIN_ID, aggregator: AGGREGATOR };
  const sign = (k: keyof typeof keys, digest: Hex, name: string) =>
    bytesToHex(c13.sign(keys[k].secretKey, hexToBytes(digest), { entropy: hexToBytes(label(`entropy.${name}`)) }));

  const r1 = label("root 1");
  const r2 = label("root 2");
  // The LeanAccount test's PQ leaf: keccak(0x10 ‖ SIG_HASH ‖ vk), with vk = keccak("vk A"), SIG_HASH = keccak("the tx SIG_HASH").
  const pathRoot = keccak256(concat([pad(toHex(0x10)), label("the tx SIG_HASH"), label("vk A")]));
  const post0 = { registry: REGISTRY, nonce: 0n, root: r1, count: 3, wallets: [W1, W2] };
  const post1 = { registry: REGISTRY, nonce: 1n, root: r2, count: 1, wallets: [W1] };
  const pathPost = { registry: REGISTRY, nonce: 0n, root: pathRoot, count: 1, wallets: [ACCOUNT] };
  const attach0 = { registry: REGISTRY, nonce: 0n, root: r1, proofHash: label("stark 1") };
  const rotate0 = { nonce: 0n, newPublicKey: bytesToHex(keys.C.publicKey) };
  const withdraw0 = { nonce: 0n, to: PAYEE, amount: parseEther("0.5") };

  const v: Record<string, Record<string, unknown>> = {};
  const add = (name: string, k: keyof typeof keys, digest: Hex, fields: Record<string, unknown>) => {
    v[name] = { signer: k, digest, ...fields, sig: sign(k, digest, name) };
  };
  add("post0", "A", postDigest(d, post0), post0);
  add("post0ByB", "B", postDigest(d, post0), post0);
  add("post1", "A", postDigest(d, post1), post1);
  add("post1ByC", "C", postDigest(d, post1), post1);
  add("attach0", "A", attachDigest(d, attach0), attach0);
  add("rotate0", "A", rotateDigest(d, rotate0), rotate0);
  add("withdraw0", "A", withdrawDigest(d, withdraw0), withdraw0);
  add("pathPost", "A", postDigest(d, pathPost), pathPost);

  const out = {
    _comment:
      "Generated by services/leanpool-node/test/pin-pq-aggregator.ts (pnpm --filter @queuebit/leanpool-node pin-vectors). Real SPHINCS- C13 signatures over PQAggregator EIP-712 digests for contracts/test/leanpool/PQAggregator.t.sol; do not edit by hand.",
    chainId: CHAIN_ID,
    registry: REGISTRY,
    aggregator: AGGREGATOR,
    account: ACCOUNT,
    payee: PAYEE,
    keys: Object.fromEntries(Object.entries(keys).map(([n, k]) => [n, bytesToHex(k.publicKey)])),
    vectors: v,
  };
  fs.mkdirSync(new URL(".", OUT), { recursive: true });
  fs.writeFileSync(OUT, `${JSON.stringify(out, (_k, x) => (typeof x === "bigint" ? x.toString() : x), 2)}\n`);
});
