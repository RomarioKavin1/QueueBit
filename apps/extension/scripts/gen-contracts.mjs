// Generates src/generated/contracts.ts from the devnet deployments (devnet/deploy/addresses.{local,public}.json), so the
// extension never carries hand-copied addresses. The ABIs come from @queuebit/account (checked against the forge
// artifacts by its abi-drift test). `--check` exits 1 when the committed file differs from what the current files
// produce (test/unit/contracts-drift.test.ts runs the same comparison).
//
// A network whose addresses file does not list the LeanAccount stack yet (an older deployment) is generated as `null`:
// the extension then says the account isn't available there. `bun run deploy` / `deploy:public` (devnet/deploy)
// rewrites the file; run this script again afterwards.
//
//   cd apps/extension && node scripts/gen-contracts.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..", "..");
export const DEPLOYMENT_FILE = join(ROOT, "devnet", "deploy", "addresses.local.json");
/** The public alt-mempool devnet (https://altmempool.forshtat.com): `bun run deploy:public`. */
export const PUBLIC_DEPLOYMENT_FILE = join(ROOT, "devnet", "deploy", "addresses.public.json");
export const TARGET = join(here, "..", "src", "generated", "contracts.ts");

/** The contracts a LeanAccount network needs (devnet/deploy/deploy.ts names). */
const STACK = [
  ["registry", "DepsRegistry"],
  ["hub", "FrameHelperHub"],
  ["keystore", "KeystoreValidator"],
  ["implementation", "LeanAccount"],
  ["factory", "LeanAccountFactory"],
  ["hook", "SpendingLimitHook"],
  ["recovery", "GuardianRecovery"],
];
/** Migration fixtures (optional: a network without them can't run the Safe / smart-account demos). */
const FIXTURES = [
  ["safeSingleton", "Safe"],
  ["safeProxyFactory", "SafeProxyFactory"],
  ["multiSend", "MultiSendCallOnly"],
  ["safeFallbackHandler", "CompatibilityFallbackHandler"],
  ["legacyAccount", "LegacyAccount"],
  ["safeMigrator", "SafeToLeanAccount"],
];

function deploymentFrom(file) {
  if (!existsSync(file)) return null;
  const d = JSON.parse(readFileSync(file, "utf8"));
  const c = d.contracts ?? {};
  if (!STACK.every(([, name]) => c[name]?.address)) return null; // an older deployment: no LeanAccount stack
  const out = { chainId: d.network.chainId };
  for (const [key, name] of STACK) out[key] = c[name].address;
  for (const [key, name] of FIXTURES) out[key] = c[name]?.address ?? null;
  out.tokens = d.tokens
    ? Object.values(d.tokens)
        .map((t) => ({
          address: t.address,
          symbol: t.symbol,
          decimals: t.decimals,
          usdPerToken: String(t.usdPerToken),
        }))
        .sort((a, b) => a.symbol.localeCompare(b.symbol))
    : [];
  return out;
}

export async function render() {
  const j = (v) => JSON.stringify(v, null, 2);
  const type = `{
  chainId: number;
  /** LeanPool's DepsRegistry (aggregators post batch roots into per-account rings). */
  registry: \`0x\${string}\`;
  hub: \`0x\${string}\`;
  keystore: \`0x\${string}\`;
  implementation: \`0x\${string}\`;
  factory: \`0x\${string}\`;
  hook: \`0x\${string}\`;
  recovery: \`0x\${string}\`;
  safeSingleton: \`0x\${string}\` | null;
  safeProxyFactory: \`0x\${string}\` | null;
  multiSend: \`0x\${string}\` | null;
  safeFallbackHandler: \`0x\${string}\` | null;
  legacyAccount: \`0x\${string}\` | null;
  safeMigrator: \`0x\${string}\` | null;
  tokens: LocalToken[];
} | null`;
  const text = `// GENERATED by scripts/gen-contracts.mjs from devnet/deploy/addresses.{local,public}.json. Do not edit.
// Regenerate after a devnet (re)deploy; test/unit/contracts-drift.test.ts fails when this is stale. A network whose
// file lists no LeanAccount stack yet is null.

/** A devnet test token devnet/deploy put on a chain (with the static price the extension shows). */
export interface LocalToken {
  address: \`0x\${string}\`;
  symbol: string;
  decimals: number;
  /** USD-6 per whole token, decimal string. */
  usdPerToken: string;
}

/** The local devnet's LeanAccount deployment (devnet/deploy/addresses.local.json), or null. */
export const localDeployment: ${type} = ${j(deploymentFrom(DEPLOYMENT_FILE))};

/** The public alt-mempool devnet's LeanAccount deployment (devnet/deploy/addresses.public.json), or null. */
export const publicDeployment: ${type} = ${j(deploymentFrom(PUBLIC_DEPLOYMENT_FILE))};
`;
  const options = (await prettier.resolveConfig(TARGET)) ?? {};
  return prettier.format(text, { ...options, filepath: TARGET });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await render();
  if (process.argv.includes("--check")) {
    const cur = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
    if (cur !== text) {
      console.error("src/generated/contracts.ts is stale: run `node scripts/gen-contracts.mjs`");
      process.exit(1);
    }
    console.log("contracts.ts is up to date");
  } else {
    writeFileSync(TARGET, text);
    console.log(`wrote ${TARGET}`);
  }
}
