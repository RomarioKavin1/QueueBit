#!/usr/bin/env python3
"""Writes contracts/test/privacy/WithdrawVkey.sol from a snarkjs Groth16 verification key (JSON).

Usage: python3 -I gen-verifier.py <withdraw.vkey> <out.sol>
The key is data (the Privacy Pools withdraw circuit's published key, final-keys/withdraw.vkey of
0xbow-io/privacy-pools-core @ df4bf73, Apache-2.0). G2 coordinates are emitted in the EIP-197 precompile order
(x_imag, x_real, y_imag, y_real), i.e. [x[1], x[0], y[1], y[0]] of the snarkjs JSON.
"""
import hashlib, json, sys

src, out = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read()
vk = json.loads(raw)
assert vk["protocol"] == "groth16" and vk["curve"] == "bn128" and vk["nPublic"] == 8, "unexpected key"

def g1(p): return [p[0], p[1]]
def g2(p): return [p[0][1], p[0][0], p[1][1], p[1][0]]

lines = []
def const(name, v): lines.append(f"    uint256 internal constant {name} = {v};")
for n, v in zip(["ALPHA_X", "ALPHA_Y"], g1(vk["vk_alpha_1"])): const(n, v)
for key, pre in [("vk_beta_2", "BETA"), ("vk_gamma_2", "GAMMA"), ("vk_delta_2", "DELTA")]:
    for n, v in zip(["X_IM", "X_RE", "Y_IM", "Y_RE"], g2(vk[key])): const(f"{pre}_{n}", v)
for i, p in enumerate(vk["IC"]):
    x, y = g1(p); const(f"IC{i}_X", x); const(f"IC{i}_Y", y)

sha = hashlib.sha256(raw).hexdigest()
body = "\n".join(lines)
open(out, "w").write(f"""// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

// GENERATED by contracts/devnet-tests/privacy/scripts/gen-verifier.py from the Privacy Pools withdraw circuit's
// verification key (0xbow-io/privacy-pools-core @ df4bf73, packages/circuits/trusted-setup/final-keys/withdraw.vkey,
// sha256 {sha}). Do not edit by hand.
/// @dev G2 points are in EIP-197 order (x_imag, x_real, y_imag, y_real).
library WithdrawVkey {{
{body}
}}
""")
print(f"wrote {out} ({len(vk['IC'])} IC points, vkey sha256 {sha})")
