// Generates contracts/test/privacy/fixtures/PoolPayerFixtures.sol: real withdraw-circuit proofs for the Foundry unit
// tests (test/privacy/PoolPayer.t.sol). The addresses are those `PoolPayerBase.setUp` deploys to: CREATE addresses
// of the Foundry test contract 0x7FA9…1496 (nonce 1 onwards), chain id 31337. The test asserts them, so a change in
// setUp's deployment order fails loudly instead of producing a context mismatch.
//   bun run fixtures
import { writeFileSync } from "node:fs";
import { getContractAddress, type Address } from "viem";
import { privateKeyToAddress } from "viem/accounts";
import { keccak256, toBytes } from "viem";
import {
  checkArtifacts, commitmentOf, contextOf, encodeFeeData, labelOf, nullifierHashOf, precommitmentOf, proveWithdrawal,
  scopeOf, secretFrom, terminate, type Note, type SolProof,
} from "./pp.ts";

const TEST: Address = "0x7FA9385bE102ac3EAc297483Dd6233D62b3e1496";
const at = (nonce: bigint) => getContractAddress({ from: TEST, nonce });
// PoolPayerBase.setUp order: 1 verifier, 2 Entrypoint impl, 3 proxy, 4 pool, 5 registry, 6 PoolPayer, 7 griefer
const POOL = at(4n), PAYER = at(6n), GRIEFER = at(7n);
const CHAIN = 31337n;
const makeAddr = (name: string) => privateKeyToAddress(keccak256(toBytes(name)));
const SENDER = makeAddr("sender"), BOB = makeAddr("bob");
const ZERO: Address = "0x0000000000000000000000000000000000000000";

checkArtifacts();
const scope = scopeOf(POOL, CHAIN);
const notes: Note[] = [1n, 2n].map((k) => ({
  value: 1_000_000_000_000_000_000n, label: labelOf(scope, k),
  nullifier: secretFrom(`fx/nullifier/${k}`), secret: secretFrom(`fx/secret/${k}`),
}));
const stateLeaves = notes.map(commitmentOf);
const aspLabels = notes.map((n) => n.label);
const WITHDRAWN = 400_000_000_000_000_000n; // 0.4 ETH of the 1 ETH note

const scenarios = [
  { name: "good", recipient: SENDER, fee: 10_000_000_000_000_000n, refundRecipient: ZERO },
  { name: "toBob", recipient: BOB, fee: 10_000_000_000_000_000n, refundRecipient: SENDER },
  { name: "feeTooHigh", recipient: SENDER, fee: 500_000_000_000_000_000n, refundRecipient: ZERO },
  { name: "griefer", recipient: GRIEFER, fee: 10_000_000_000_000_000n, refundRecipient: GRIEFER },
];

const fmt = (x: bigint) => x.toString();
const arr = (xs: bigint[]) => `[${xs.map(fmt).join(", ")}]`;
const solProof = (p: SolProof) =>
  `PrivacyPoolsTypes.WithdrawProof({pA: ${arr(p.pA)}, pB: [${arr(p.pB[0])}, ${arr(p.pB[1])}], pC: ${arr(p.pC)}, pubSignals: ${arr(p.pubSignals)}})`;

let body = "";
let stateRoot = 0n, aspRoot = 0n;
for (const s of scenarios) {
  const data = encodeFeeData({ recipient: s.recipient, feeRecipient: PAYER, fee: s.fee, refundRecipient: s.refundRecipient });
  const context = contextOf({ processooor: PAYER, data }, scope);
  const r = await proveWithdrawal({
    note: notes[0], withdrawn: WITHDRAWN, stateLeaves, aspLabels, context,
    newNullifier: secretFrom(`fx/new-nullifier/${s.name}`), newSecret: secretFrom(`fx/new-secret/${s.name}`),
  });
  stateRoot = r.stateRoot; aspRoot = r.aspRoot;
  console.log(`${s.name}: proved in ${r.ms} ms`);
  body += `
    function ${s.name}() internal pure returns (PrivacyPoolsTypes.Withdrawal memory w, PrivacyPoolsTypes.WithdrawProof memory p) {
        w = PrivacyPoolsTypes.Withdrawal({processooor: ${PAYER}, data: hex"${data.slice(2)}"});
        p = ${solProof(r.proof)};
    }
`;
}

const out = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

import {PrivacyPoolsTypes} from "../../../src/privacy/IPrivacyPools.sol";

// GENERATED by contracts/devnet-tests/privacy/src/gen-fixtures.ts (bun run fixtures). Do not edit by hand.
// Real Groth16 proofs of the Privacy Pools withdraw circuit (withdraw.zkey sha256 2a893b42…de677), for the addresses
// PoolPayerBase.setUp deploys to on chain id ${CHAIN}.
library PoolPayerFixtures {
    address internal constant POOL = ${POOL};
    address internal constant POOL_PAYER = ${PAYER};
    address internal constant GRIEFER = ${GRIEFER};
    uint256 internal constant SCOPE = ${scope};
    uint256 internal constant PRECOMMITMENT_1 = ${precommitmentOf(notes[0].nullifier, notes[0].secret)};
    uint256 internal constant PRECOMMITMENT_2 = ${precommitmentOf(notes[1].nullifier, notes[1].secret)};
    uint256 internal constant NOTE_VALUE = ${notes[0].value};
    uint256 internal constant WITHDRAWN = ${WITHDRAWN};
    uint256 internal constant NULLIFIER_HASH_1 = ${nullifierHashOf(notes[0].nullifier)};
    uint256 internal constant STATE_ROOT = ${stateRoot};
    /// The ring index the second deposit's root lands at (currentRootIndex 0 -> 1 -> 2).
    uint32 internal constant STATE_ROOT_INDEX = 2;
    uint256 internal constant ASP_ROOT = ${aspRoot};
${body}}
`;
const path = new URL("../../../test/privacy/fixtures/PoolPayerFixtures.sol", import.meta.url).pathname;
writeFileSync(path, out);
console.log(`wrote ${path}`);
await terminate();
process.exit(0);
